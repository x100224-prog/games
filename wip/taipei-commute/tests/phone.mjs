import { chromium, devices } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 1 });
const page = await ctx.newPage();
const logs = []; page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
const ev = (f) => page.evaluate(f);
await page.goto('http://localhost:8765/index.html');
await page.waitForFunction(() => window.__tc && window.__tc.G.state === 'menu');
await page.waitForTimeout(3000);
await page.screenshot({ path: 'shots/p1_menu.png' });
await ev(() => { const G = window.__tc.G; G.cfg.di = 7; G.cfg.home = G.meta.homes[7][1]; const h = G.cfg.home; G.cfg.work = G.meta.works.find(w => Math.hypot(w.x - h.x, w.z - h.z) > 2000); G.cfg.car = 'gas'; G.carPicked = true; document.getElementById('btnGo').disabled = false; document.getElementById('btnGo').click(); });
await page.waitForFunction(() => window.__tc.G.state === 'room', null, { timeout: 90000 });
await page.tap('#view');
await ev(() => { const P = window.__tc.P; P.x = 1.2; P.z = -2.2; });
await page.tap('#btnAct');
await page.waitForFunction(() => window.__tc.G.state === 'walk', null, { timeout: 8000 });
await page.waitForTimeout(600);
await ev(() => { const { P, G } = window.__tc; P.x = G.car.x - Math.cos(G.car.psi) * 1.8; P.z = G.car.z + Math.sin(G.car.psi) * 1.8; });
await page.waitForTimeout(400);
await page.tap('#btnAct');
await page.waitForFunction(() => window.__tc.G.state === 'drive', null, { timeout: 8000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/p2_drive.png' });
console.log(logs.join('\n'));
await browser.close();
