import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const out = process.argv[2] || 'shots';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 760 } });
const logs = [];
page.on('console', m => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message + '\n' + e.stack));
await page.goto('http://localhost:8765/index.html');
await page.waitForFunction(() => window.__tc && window.__tc.G.state === 'menu', null, { timeout: 30000 });
await page.waitForTimeout(6000);
await page.screenshot({ path: out + '/01_menu.png' });
// 選中山區
const di = await page.evaluate(() => window.__tc.G.meta.districts.findIndex(d => d.name === '中山區'));
await page.click(`#distMap path[data-i="${di}"]`, { force: true });
await page.waitForTimeout(400);
await page.click('#homeOpts .opt >> nth=0');
await page.waitForTimeout(400);
await page.click('#workOpts .opt >> nth=0');
await page.click('#carOpts .opt[data-car="ev"]');
await page.waitForTimeout(3000);
await page.screenshot({ path: out + '/02_menu_filled.png' });
await page.click('#btnGo');
await page.waitForFunction(() => window.__tc.G.state === 'room', null, { timeout: 90000 });
await page.waitForTimeout(800);
await page.screenshot({ path: out + '/03_room.png' });
const info = await page.evaluate(() => { const G = window.__tc.G; return { home: G.cfg.home, work: G.cfg.work, bay: G.homeBay && { x: G.homeBay.x, z: G.homeBay.z, road: G.homeBay.edge.name }, car: { x: G.car.x, z: G.car.z } }; });
console.log(JSON.stringify(info));
// 走到門口
await page.evaluate(() => { const P = window.__tc.P; P.x = 1.2; P.z = -2.2; P.yaw = 0; });
await page.waitForTimeout(200);
await page.keyboard.press('KeyE');
await page.waitForFunction(() => window.__tc.G.state === 'walk', null, { timeout: 5000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + '/04_street.png' });
// 轉向車子
await page.evaluate(() => { const { P, G } = window.__tc; P.yaw = Math.atan2(-(G.car.x - P.x), -(G.car.z - P.z)); P.pitch = -0.1; });
await page.waitForTimeout(1500);
await page.screenshot({ path: out + '/05_look_car.png' });
await page.evaluate(() => { const { P, G } = window.__tc; P.x = G.car.x - Math.cos(G.car.psi) * 1.8; P.z = G.car.z + Math.sin(G.car.psi) * 1.8; });
await page.waitForTimeout(300);
await page.keyboard.press('KeyE');
await page.waitForFunction(() => window.__tc.G.state === 'drive', null, { timeout: 5000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: out + '/06_cockpit.png' });
await page.keyboard.down('KeyW'); await page.waitForTimeout(4000); await page.keyboard.up('KeyW');
await page.waitForTimeout(500);
await page.screenshot({ path: out + '/07_driving.png' });
await page.keyboard.press('KeyC'); await page.waitForTimeout(1200);
await page.screenshot({ path: out + '/08_chase.png' });
const st = await page.evaluate(() => { const { G } = window.__tc; return { v: G.car.v, x: G.car.x, z: G.car.z, cars: G.traffic.cars.length, cells: G.world.cells.size, loaded: G.world.loadedCount, bumps: G.car.bumps, edge: G.car.edge && G.car.edge.name, renderer: null }; });
console.log(JSON.stringify(st));
console.log(logs.slice(0, 40).join('\n'));
await browser.close();
