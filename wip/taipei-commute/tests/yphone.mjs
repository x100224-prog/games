import { chromium, devices } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const land = process.argv[2] === 'land';
const dev = devices['iPhone 13'];
const ctx = await browser.newContext({ ...dev, deviceScaleFactor: 1, viewport: land ? { width: 844, height: 390 } : dev.viewport });
const page = await ctx.newPage();
const logs = []; page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
const ev = (f) => page.evaluate(f); const tag = land ? 'L' : 'P';
page.setDefaultTimeout(300000);
await page.goto('http://localhost:8766/index.html#lowq');
await page.waitForFunction(() => window.__tc && window.__tc.G.state === 'title');
await page.waitForTimeout(2000);
await page.screenshot({ path: `shots/ph${tag}1_title.png` });
await page.tap('#btnStart');
await page.waitForFunction(() => window.__tc.G.state === 'walk');
await page.tap('#view');
await page.waitForTimeout(2500);
await page.screenshot({ path: `shots/ph${tag}2_walk.png` });
await ev(() => { const { P, car } = window.__tc; P.x = car.x - Math.cos(car.psi) * 1.8; P.z = car.z + Math.sin(car.psi) * 1.8; });
await page.waitForTimeout(1500);
await page.tap('#btnAct');
await page.waitForFunction(() => window.__tc.G.state === 'drive');
await page.waitForTimeout(3000);
await page.screenshot({ path: `shots/ph${tag}3_seat.png` });
await page.tap('#seatGo');
await page.waitForTimeout(3000);
await page.screenshot({ path: `shots/ph${tag}4_drive.png` });
console.log(JSON.stringify(await ev(() => ({ touch: window.__tc.G && document.body.classList.contains('touch'), touchUI: !document.getElementById('touch').hidden }))));
console.log(logs.join('\n')); await browser.close();
